import { atomicWriteSync, safePath } from "./files.ts";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { missingFields, splitFrontMatter } from "./front-matter.ts";
import type { Service } from "../plugins/types.ts";

/**
 * Builds a service folder's index.md from its items' front matter, so every index has
 * the same columns and agents read them the same way: read the index, then open only the
 * file needed.
 */

export const INDEX_FILE = "index.md";

export interface IndexResult {
  file: string;
  items: number;
  /** Markdown files skipped because their front matter lacks the common fields. */
  skipped: Array<{ file: string; missing: string[] }>;
}

interface Row {
  id: string;
  title: string;
  status: string;
  updated: string;
  link: string;
  mine: boolean | null;
  why: string | null;
}

/** Why an item is here, in one word. Older files without "via" are told apart by inScope. */
function why(data: Record<string, unknown>): string | null {
  if (typeof data.via === "string") return data.via;
  if (data.inScope === true) return "scope";
  if (data.inScope === false) return "linked";
  return null;
}

function markdownFiles(folder: string, include: (file: string) => boolean): string[] {
  return readdirSync(folder, { recursive: true, encoding: "utf8" })
    // Only the folder's own index.md is skipped: items may be called index.md, like Confluence pages.
    .filter((file) => file.endsWith(".md") && file !== INDEX_FILE && include(file.split(path.sep).join("/")))
    .filter((file) => !file.split(path.sep).some((part) => part.startsWith(".")))
    .sort();
}

function text(value: unknown): string {
  if (value instanceof Date) return value.toISOString();
  return typeof value === "string" ? value : value === undefined || value === null ? "" : String(value);
}

/** Keeps a cell on one line and stops it breaking the table. */
function cell(value: string): string {
  return value.replace(/\r?\n/g, " ").replace(/\|/g, "\\|").trim();
}

/** `include` limits which Markdown files are items, like only each PR's pr-description.md. */
export function buildIndex(folder: string, title: string, include: (file: string) => boolean = () => true): IndexResult {
  const rows: Row[] = [];
  const skipped: IndexResult["skipped"] = [];

  for (const file of markdownFiles(folder, include)) {
    const { data } = splitFrontMatter(readFileSync(path.join(folder, file), "utf8"));
    const missing = missingFields(data);
    if (missing.length > 0 || !data) {
      skipped.push({ file, missing });
      continue;
    }
    rows.push({
      id: text(data.id),
      title: text(data.title),
      status: text(data.status),
      updated: text(data.updated).slice(0, 10),
      link: file.split(path.sep).join("/"),
      mine: typeof data.mine === "boolean" ? data.mine : null,
      why: why(data),
    });
  }

  // Most recently changed first: that's what people and agents scan for.
  rows.sort((a, b) => b.updated.localeCompare(a.updated) || a.id.localeCompare(b.id));

  const lines = [
    `# ${title}`,
    "",
    "Generated by dev from each file's front matter. Don't edit: the next sync rewrites it.",
    "",
    `${rows.length} item${rows.length === 1 ? "" : "s"}.`,
    "",
  ];

  // Mine and Why only appear where the service records them, so other indexes stay as they are.
  const showMine = rows.some((row) => row.mine !== null);
  const showWhy = rows.some((row) => row.why !== null);
  if (showWhy) {
    lines.push("Why: scope is the work this workspace follows. parent, linked and pulled are context fetched because something points to them; former left the scope.", "");
  }

  if (rows.length > 0) {
    const headings = ["ID", "Title", "Status", ...(showMine ? ["Mine"] : []), ...(showWhy ? ["Why"] : []), "Updated"];
    lines.push(`| ${headings.join(" | ")} |`, `| ${headings.map(() => "---").join(" | ")} |`);
    for (const row of rows) {
      const cells = [
        `[${cell(row.id)}](${encodeURI(row.link)})`,
        cell(row.title),
        cell(row.status),
        ...(showMine ? [row.mine ? "yes" : ""] : []),
        ...(showWhy ? [row.why ?? ""] : []),
        row.updated,
      ];
      lines.push(`| ${cells.join(" | ")} |`);
    }
    lines.push("");
  }

  const file = safePath(folder, INDEX_FILE);
  atomicWriteSync(file, lines.join("\n"));
  return { file, items: rows.length, skipped };
}

/** Every item file of a service, relative to the workspace root. */
export function serviceFiles(root: string, service: Service): string[] {
  const name = service.index?.folder ?? service.id;
  const folder = path.join(root, name);
  return existsSync(folder) ? markdownFiles(folder, service.index?.include ?? (() => true)).map((file) => `${name}/${file.split(path.sep).join("/")}`) : [];
}

/** Rebuilds a service's index.md with the folder, title and files it declares. Null when the folder doesn't exist yet. */
export function buildServiceIndex(root: string, service: Service): IndexResult | null {
  const folder = path.join(root, service.index?.folder ?? service.id);
  return existsSync(folder) ? buildIndex(folder, service.index?.title ?? service.title, service.index?.include) : null;
}
